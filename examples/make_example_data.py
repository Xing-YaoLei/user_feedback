"""生成 examples/ 下的示例 CSV（v1 / v2 规则与读数）。

场景覆盖：
* M-101 累计表：首条无基线异常、月中（03-16）从冲压车间转涂装车间；
* M-102 增量表：电价缺口 03-15~03-20（no_tariff），v2 补规则后恢复；
* M-103 增量表：归属缺口（no_attribution），v2 补归属后恢复；
* M-104 增量表：归属区间重叠（multiple_attribution），v2 修区间后恢复；
* M-105 增量表：v2 删除归属规则，原本正常的读数变成新异常；
* 读数时间混用朴素时间、Z 偏移与 +08:00 偏移，验证北京时间换算。
"""

import csv
import os

HERE = os.path.dirname(os.path.abspath(__file__))

DAYS = range(1, 21)  # 2026-03-01 .. 2026-03-20


def write_csv(name, header, rows):
    with open(os.path.join(HERE, name), "w", encoding="utf-8", newline="") as fh:
        writer = csv.writer(fh)
        writer.writerow(header)
        writer.writerows(rows)


def main():
    # ---- 读数（累计模式与增量模式各自只写所需列） -----------------------
    cumulative_rows = []
    incremental_rows = []
    cumulative = 1000.0
    for d in DAYS:
        # M-101 累计读数，每日 08:00，每天 +120
        cumulative += 120.0
        cumulative_rows.append(["M-101", f"2026-03-{d:02d} 08:00:00", f"{cumulative:.1f}"])
        # M-102 增量 100 kWh，10:00；03-18 用 Z 偏移表达同一北京时间时刻
        if d == 18:
            incremental_rows.append(["M-102", "2026-03-18T02:00:00Z", "100"])
        else:
            incremental_rows.append(["M-102", f"2026-03-{d:02d} 10:00:00", "100"])
        # M-103 增量；03-11 用 UTC 偏移（23:30Z = 次日 07:30 北京）演示业务日换算
        if d == 11:
            incremental_rows.append(["M-103", "2026-03-10T23:30:00Z", "100"])
        elif d == 5:
            incremental_rows.append(["M-103", "2026-03-05T00:30:00+08:00", "100"])
        else:
            incremental_rows.append(["M-103", f"2026-03-{d:02d} 10:00:00", "100"])
        # M-104 增量
        incremental_rows.append(["M-104", f"2026-03-{d:02d} 10:00:00", "100"])
        # M-105 只到 03-12
        if d <= 12:
            incremental_rows.append(["M-105", f"2026-03-{d:02d} 10:00:00", "100"])

    # 累计表与增量表不能共用一个文件（整表二选一），分两个文件存放
    write_csv(
        "readings_cumulative.csv",
        ["meter_id", "reading_time", "meter_reading"],
        cumulative_rows,
    )
    write_csv(
        "readings.csv",
        ["meter_id", "reading_time", "consumption_kwh"],
        incremental_rows,
    )

    # ---- v1 归属 --------------------------------------------------------
    write_csv(
        "attr.csv",
        ["rule_id", "meter_id", "workshop_id", "workshop_name", "valid_from", "valid_to"],
        [
            ["A-M101-01", "M-101", "WS-A", "冲压车间", "2026-02-01 00:00:00", ""],
            ["A-M102-01", "M-102", "WS-A", "冲压车间", "2026-02-01 00:00:00", ""],
            ["A-M103-01", "M-103", "WS-B", "焊接车间", "2026-02-01 00:00:00", "2026-03-10 00:00:00"],
            # 03-05 起与 A-M104-02 区间重叠 → multiple_attribution
            ["A-M104-01", "M-104", "WS-B", "焊接车间", "2026-02-01 00:00:00", ""],
            ["A-M104-02", "M-104", "WS-C", "涂装车间", "2026-03-05 00:00:00", ""],
            ["A-M105-01", "M-105", "WS-A", "冲压车间", "2026-03-01 00:00:00", "2026-03-10 00:00:00"],
        ],
    )

    # ---- v2 归属 --------------------------------------------------------
    write_csv(
        "attr_v2.csv",
        ["rule_id", "meter_id", "workshop_id", "workshop_name", "valid_from", "valid_to"],
        [
            # 月中转车间：03-16 起 M-101 归涂装车间（同 rule_id 修改 + 新增一条）
            ["A-M101-01", "M-101", "WS-A", "冲压车间", "2026-02-01 00:00:00", "2026-03-16 00:00:00"],
            ["A-M101-02", "M-101", "WS-C", "涂装车间", "2026-03-16 00:00:00", ""],
            ["A-M102-01", "M-102", "WS-A", "冲压车间", "2026-02-01 00:00:00", ""],
            # 补上 M-103 的归属缺口
            ["A-M103-01", "M-103", "WS-B", "焊接车间", "2026-02-01 00:00:00", "2026-03-10 00:00:00"],
            ["A-M103-02", "M-103", "WS-B", "焊接车间", "2026-03-10 00:00:00", ""],
            # 修复重叠：A-M104-01 收口到 03-05
            ["A-M104-01", "M-104", "WS-B", "焊接车间", "2026-02-01 00:00:00", "2026-03-05 00:00:00"],
            ["A-M104-02", "M-104", "WS-C", "涂装车间", "2026-03-05 00:00:00", ""],
            # A-M105-01 被删除 → M-105 03-01..03-09 的读数失去归属
        ],
    )

    # ---- v1 电价（WS-A 在 03-15~03-20 之间有缺口） ----------------------
    write_csv(
        "tariff.csv",
        ["rule_id", "workshop_id", "valid_from", "valid_to", "price_per_kwh"],
        [
            ["T-WS-A-01", "WS-A", "2026-02-01 00:00:00", "2026-03-15 00:00:00", "0.82"],
            ["T-WS-A-02", "WS-A", "2026-03-20 00:00:00", "", "0.90"],
            ["T-WS-B-01", "WS-B", "2026-02-01 00:00:00", "", "0.70"],
            ["T-WS-C-01", "WS-C", "2026-02-01 00:00:00", "", "0.75"],
        ],
    )

    # ---- v2 电价：调价 + 填补缺口 ---------------------------------------
    write_csv(
        "tariff_v2.csv",
        ["rule_id", "workshop_id", "valid_from", "valid_to", "price_per_kwh"],
        [
            # 同 rule_id 调价 0.82 → 0.80
            ["T-WS-A-01", "WS-A", "2026-02-01 00:00:00", "2026-03-15 00:00:00", "0.80"],
            # 新增规则填补缺口
            ["T-WS-A-03", "WS-A", "2026-03-15 00:00:00", "2026-03-20 00:00:00", "0.85"],
            ["T-WS-A-02", "WS-A", "2026-03-20 00:00:00", "", "0.90"],
            ["T-WS-B-01", "WS-B", "2026-02-01 00:00:00", "", "0.70"],
            ["T-WS-C-01", "WS-C", "2026-02-01 00:00:00", "", "0.75"],
        ],
    )
    print("示例数据已写入", HERE)


if __name__ == "__main__":
    main()
